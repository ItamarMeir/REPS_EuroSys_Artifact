#!/usr/bin/env python3
"""Summarise data/p1 (run_p1.sh) -> data/p1/summary.md (+ stdout). usage: summarize_p1.py [data/p1 dir]"""
import os, re, subprocess, sys, glob, hashlib
S = os.path.dirname(os.path.abspath(__file__))
D = sys.argv[1] if len(sys.argv) > 1 else os.path.join(S, "..", "data", "p1")
D = os.path.abspath(D)
minrtt = float(open(D + "/minrtt.txt").read().split()[0])
NEVER = "1000000000"
def row(tag):
    f = "%s/%s.out" % (D, tag)
    if not os.path.exists(f): return None
    r = subprocess.run([sys.executable, S + "/summarize_run.py", tag, f, "%s/%s.tsv" % (D, tag), "1027"], capture_output=True, text=True).stdout.split("\t")
    txt = open(f, errors="replace").read()
    m = re.search(r"ROUTING_CONV decisions_to_known_dead=(\d+) drops_before_known=(\d+) drops_after_known=(\d+)", txt)
    rc = re.search(r"rc=(\d+)", txt)
    return dict(fin=int(r[1]), started=int(r[2]), cct=float(r[3]), mean=float(r[4]), p99=float(r[5]), trims=int(r[6]), drops=int(r[7]),
                rts=int(r[9]), rtos=int(r[10]), abort=r[13].strip(), dec=int(m[1]) if m else None, db=int(m[2]) if m else None,
                da=int(m[3]) if m else None, rc=rc[1] if rc else "?")
def fmt(x, nd=1): return "-" if x is None else ("%.*f" % (nd, x) if isinstance(x, float) else str(x))
STR = ["ofan", "ecmp_ar", "ecmp_host", "ecmp_rr", "reps"]
def gstr(g): return "never" if g == NEVER else g
out = []
P = out.append
P("# P1 results: routing-convergence gates G3/G5 \n")
P("Setup: 54-host k=6 3-tier 400G, derangement 4 MiB x54 (seed 42), nscc, `-q 193 -ecn 19 19`, failure Agg0<->Core0 (both directions), never recovers.")
P("Generated by `scripts/run_p1.sh` + `scripts/summarize_p1.py`. minRTT (single 4096 B inter-pod flow, FCT = completion at the sender) = **%.3f us**.\n" % minrtt)
P("## Healthy reference (no failure)\n")
P("| strategy | fin/54 | CCT us | mean FCT us | RTOs | trims |"); P("|---|---|---|---|---|---|")
for s in STR:
    r = row("%s_G0_fnone" % s)
    if r: P("| %s | %d | %s | %s | %d | %d |" % (s, r["fin"], fmt(r["cct"]), fmt(r["mean"]), r["rtos"], r["trims"]))
P("")
# G3
P("## G3 - timing / no cheating\n")
P("Tag `<strat>_G<G>_f<fail_us>`. Gate: `decisions_to_known_dead == 0` everywhere; `drops_before_known > 0` when G > 0 and the failure is mid-run.\n")
for title, g, f in [("G=50us, failure at t=20us (known at t=70us)", "50", "20"), ("G=20us, failure at 20us (known at 40us)", "20", "20"),
                    ("G=0, failure at t=0.01us (static)", "0", "0.01"), ("G=never (1e9), failure at t=0.01us (legacy S7-like)", NEVER, "0.01"),
                    ("G=never (1e9), failure at t=20us", NEVER, "20")]:
    P("### %s\n" % title)
    P("| strategy | fin/54 | CCT us | mean FCT us | RTOs | drops (queue) | trims | decisions_to_known_dead | drops_before_known | drops_after_known |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for s in STR:
        r = row("%s_G%s_f%s" % (s, g, f))
        if r is None: continue
        P("| %s | %d | %s | %s | %d | %d | %d | %s | %s | %s |" % (s, r["fin"], fmt(r["cct"]), fmt(r["mean"]), r["rtos"], r["drops"], r["trims"], fmt(r["dec"]), fmt(r["db"]), fmt(r["da"])))
    P("")
P("`drops (queue)` is the sum of `drops` in `-log_queue_stats` (buffer-overflow/NDP-less drops); packets freed by the failed `Pipe` are NOT in it (they appear only in `drops_before/after_known`).\n")
P("### drops_after_known vs drain bound (G=50, failure at 20us)\n")
P("A queue at the dead pipe holds at most 193 pkts (800 950 B) = 16.0 us at 400G; two directions (Agg0->Core0, Core0->Agg0) => at most ~386 pkts can still drain into the dead pipe at t_known, plus the switch-latency pipe contents. Observed:\n")
for s in STR:
    r = row("%s_G50_f20" % s)
    if r: P("- %s: drops_after_known = %d pkts (= %.1f us of one 400G link at 4150 B/pkt; %.1f%% of the 386-pkt queue bound)" % (s, r["da"], r["da"] * 4150 * 8 / 400e3, 100.0 * r["da"] / 386))
P("")
# G5
P("## G5 - sweep of G (failure at 20us for G>0; G=0 is the static case with failure at 0.01us)\n")
gl = [("0", "0.01", "0 (static, f=0.01)"), ("0", "20", "0 (mid-run f=20, cheating ref)")] + [(("%.3f" % (k * minrtt)), "20", "%dxRTT=%.1f" % (k, k * minrtt)) for k in (1, 2, 5, 10)] + [(NEVER, "20", "never")]
for metric, key, nd in [("flows finished (of 54)", "fin", 0), ("CCT us (last finish)", "cct", 1), ("mean FCT us", "mean", 1), ("RTOs (sum over flows)", "rtos", 0),
                        ("queue drops (log_queue_stats)", "drops", 0), ("trims", "trims", 0), ("pipe drops before t_known / after", "dba", 0)]:
    P("### %s\n" % metric)
    P("| strategy | " + " | ".join(l[2] for l in gl) + " |"); P("|---|" + "---|" * len(gl))
    for s in ["ofan", "ecmp_ar", "ecmp_host", "reps"]:
        cells = []
        for g, f, _ in gl:
            r = row("%s_G%s_f%s" % (s, g, f))
            if r is None: cells.append("-")
            elif key == "dba": cells.append("%d / %d" % (r["db"], r["da"]))
            else: cells.append(fmt(r[key], nd) if key != "fin" else str(r["fin"]))
        P("| %s | %s |" % (s, " | ".join(cells)))
    P("")
# G4
P("## G4 - balance under static failure (G=0, failure at 0.01us)\n")
P("```")
P(subprocess.run([sys.executable, S + "/check_balance_valid.py", D + "/ofan_G0_f0.01_ofancounts.tsv"], capture_output=True, text=True).stdout.strip())
P("```\n```")
P(subprocess.run([sys.executable, S + "/link_overload_valid.py", "0", "0"] + ["%s=%s/%s_G0_f0.01.tsv" % (a, D, a) for a in ["ofan", "ecmp_ar", "ecmp_host", "reps"]], capture_output=True, text=True).stdout.strip())
P("```\n")
# determinism
P("## Determinism (ofan, G=50, failure 20us)\n")
hs = {}
for suf in ["", "_rep2", "_rep3", "_check", "_counts"]:
    f = "%s/ofan_G50_f20%s.out" % (D, suf)
    if os.path.exists(f):
        t = "\n".join(l for l in open(f, errors="replace").read().splitlines() if not l.startswith("ROUTING_CHECK"))
        hs[suf or "base"] = hashlib.md5(t.encode()).hexdigest()
        qs = f.replace(".out", ".tsv"); hs[(suf or "base") + " queue-stats"] = hashlib.md5(open(qs, "rb").read()).hexdigest()
for k, v in hs.items(): P("- %s: %s" % (k, v))
P("\n(base vs _rep2 vs _rep3 must be identical; `_check` (-routing_check) and `_counts` (-log_ofan_counts) change extra events/logging; stdout is compared with ROUTING_CHECK lines removed.)\n")
for suf in ["_check"]:
    f = "%s/ofan_G50_f20%s.out" % (D, suf)
    if os.path.exists(f):
        P("`-routing_check` run: " + " ; ".join(re.findall(r"ROUTING_CHECK[^\n]*", open(f).read())) + "\n")
open(D + "/summary.md", "w").write("\n".join(out) + "\n")
print("\n".join(out))
