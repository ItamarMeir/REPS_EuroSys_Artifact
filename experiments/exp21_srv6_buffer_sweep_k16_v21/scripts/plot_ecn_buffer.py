#!/usr/bin/env python3
"""
plot_ecn_buffer.py — Exact ECN counts + host-0 buffer dynamics for B=1 and B=2.

Inputs (generated by run_ecn_buffer.sh):
  data/run_b1_nscc_s42.out   data/run_b2_nscc_s42.out   — flow finish lines with ecn_acks
  data/buf_b1_nscc_s42.csv   data/buf_b2_nscc_s42.csv   — per-ACK buffer state for host 0

Output:
  plots/ecn_buffer_dynamics.png
"""
import re
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

SCRIPT_DIR = Path(__file__).resolve().parent
EXP_DIR    = SCRIPT_DIR.parent
DATA_DIR   = EXP_DIR / "data"
PLOTS_DIR  = EXP_DIR / "plots"

FINISH_RE = re.compile(
    r"finished at\s+([\d.]+)\s+flowSize\s+\d+.*?\becn_acks\s+(\d+)", re.IGNORECASE
)

COLORS = {1: "#2171b5", 2: "#f97f1f"}
LABELS = {1: "B=1  (single-path buffer)", 2: "B=2  (two-path buffer)"}


def parse_evs(s):
    if pd.isna(s) or str(s).strip() in ("", "nan"):
        return []
    parts = str(s).split("|")
    result = []
    for p in parts:
        try:
            result.append(int(float(p.strip())))
        except (ValueError, OverflowError):
            pass
    return result


def load_flows(B):
    path = DATA_DIR / f"run_b{B}_nscc_s42.out"
    if not path.exists():
        print(f"ERROR: {path} not found", file=sys.stderr)
        sys.exit(1)
    records = []
    for line in path.read_text().splitlines():
        m = FINISH_RE.search(line)
        if m:
            records.append({"fct_us": float(m.group(1)), "ecn_acks": int(m.group(2))})
    return pd.DataFrame(records)


def load_buf(B):
    path = DATA_DIR / f"buf_b{B}_nscc_s42.csv"
    if not path.exists():
        print(f"ERROR: {path} not found", file=sys.stderr)
        sys.exit(1)
    df = pd.read_csv(path)
    df["evs"]  = df["buf_contents"].apply(parse_evs)
    df["n_evs"] = df["evs"].apply(len)
    return df


def main():
    PLOTS_DIR.mkdir(parents=True, exist_ok=True)

    flows = {B: load_flows(B) for B in [1, 2]}
    bufs  = {B: load_buf(B)   for B in [1, 2]}

    for B in [1, 2]:
        ecn = flows[B]["ecn_acks"]
        bdf = bufs[B]
        changes = (bdf["buf_contents"].astype(str) != bdf["buf_contents"].astype(str).shift()).sum()
        print(f"B={B}: mean_ecn={ecn.mean():.1f}  median={ecn.median():.0f}  "
              f"min={ecn.min()}  max={ecn.max()}  mean_fct={flows[B]['fct_us'].mean():.1f}µs")
        print(f"       host-0: {bdf['ecn'].sum()} ECN marks / {len(bdf)} ACKs "
              f"({100*bdf['ecn'].mean():.1f}%)  buf_changes={changes}")

    # ── figure: 3 rows × 2 cols ───────────────────────────────────────────────
    fig = plt.figure(figsize=(14, 11))
    gs  = fig.add_gridspec(3, 2, hspace=0.48, wspace=0.35)

    # Row 0: ECN count histograms
    for col, B in enumerate([1, 2]):
        ax  = fig.add_subplot(gs[0, col])
        ecn = flows[B]["ecn_acks"]
        bins = np.arange(0, ecn.max() + 50, 25)
        ax.hist(ecn, bins=bins, color=COLORS[B], edgecolor="white", linewidth=0.3)
        ax.axvline(ecn.mean(),   color="black", linewidth=1.2, linestyle="--",
                   label=f"mean={ecn.mean():.0f}")
        ax.axvline(ecn.median(), color="grey",  linewidth=1.0, linestyle=":",
                   label=f"median={ecn.median():.0f}")
        ax.set_xlabel("ECN-marked ACKs received per flow", fontsize=9)
        ax.set_ylabel("Number of flows", fontsize=9)
        ax.set_title(f"{LABELS[B]}\nECN count distribution — 1024 flows, NSCC, 8 MB, seed=42",
                     fontsize=9)
        ax.legend(fontsize=8)
        ax.grid(axis="y", linestyle="--", linewidth=0.4, alpha=0.5)
        ax.set_axisbelow(True)

    # Row 1: ECN count vs FCT scatter (both B on same axes)
    ax_s = fig.add_subplot(gs[1, :])
    for B in [1, 2]:
        sub = flows[B]
        ax_s.scatter(sub["fct_us"], sub["ecn_acks"],
                     alpha=0.35, s=6, color=COLORS[B], label=LABELS[B])
    ax_s.set_xlabel("Flow completion time (µs)", fontsize=9)
    ax_s.set_ylabel("ECN-marked ACKs per flow", fontsize=9)
    ax_s.set_title("ECN count vs FCT — all 1024 flows, NSCC, 8 MB, seed=42", fontsize=9)
    ax_s.legend(fontsize=8)
    ax_s.grid(linestyle="--", linewidth=0.4, alpha=0.4)
    ax_s.set_axisbelow(True)

    # Row 2: Buffer dynamics for host 0
    for col, B in enumerate([1, 2]):
        ax  = fig.add_subplot(gs[2, col])
        bdf = bufs[B]
        cmap = plt.cm.tab10

        # One scatter series per buffer slot
        slot_times = [[] for _ in range(B)]
        slot_evs   = [[] for _ in range(B)]
        for _, row in bdf.iterrows():
            for slot, ev in enumerate(row["evs"][:B]):
                slot_times[slot].append(row["time_us"])
                slot_evs[slot].append(ev)

        for slot in range(B):
            if slot_times[slot]:
                ax.scatter(slot_times[slot], slot_evs[slot],
                           s=1.5, alpha=0.5,
                           color=cmap(slot / max(B, 1)),
                           label=f"slot {slot}")

        # ECN marks as red ticks at the top
        ecn_t = bdf[bdf["ecn"] == 1]["time_us"]
        ax.scatter(ecn_t, [65] * len(ecn_t),
                   s=2, color="red", alpha=0.4, marker="|", label=f"ECN ({len(ecn_t)})")

        ax.set_xlabel("Time (µs)", fontsize=9)
        ax.set_ylabel("EV value in buffer slot", fontsize=9)
        ax.set_title(
            f"B={B} — host-0 buffer contents per ACK\n"
            f"({len(ecn_t)} ECN marks / {len(bdf)} ACKs = {100*bdf['ecn'].mean():.1f}%)",
            fontsize=9)
        ax.set_ylim(-2, 68)
        ax.legend(fontsize=7, markerscale=4, loc="lower right")
        ax.grid(linestyle="--", linewidth=0.3, alpha=0.4)
        ax.set_axisbelow(True)

    out = PLOTS_DIR / "ecn_buffer_dynamics.png"
    fig.savefig(out, dpi=150, bbox_inches="tight")
    plt.close(fig)
    print(f"\nSaved {out}")


if __name__ == "__main__":
    main()
