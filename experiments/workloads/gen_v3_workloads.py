#!/usr/bin/env python3
"""
v3 workload generators.

Re-uses the pure-permutation TM at
  htsim/sim/datacenter/connection_matrices/perm_n128_s8388608.cm
and the composite TM produced by gen_composite.py (this dir).

Generates two new TMs alongside this script:

  mice_heavy.cm     -- 256 mice (32KB) + 16 elephants (4MB)
  elephant_heavy.cm -- 64 elephants (16MB)

Start times in the .cm format are picoseconds. The tokenized parser treats
numeric `start` as picoseconds when an `id` field is present.
"""
import os, random
HERE = os.path.dirname(os.path.abspath(__file__))

N = 128
US = 1_000_000  # 1 microsecond in picoseconds
rng = random.Random(20)

def write_cm(path, lines):
    n = len(lines)
    with open(path, "w") as f:
        f.write(f"Nodes {N}\nConnections {n}\n")
        for ln in lines:
            f.write(ln + "\n")
    print(f"wrote {path}: connections={n}")

# ---------------- mice-heavy ----------------
# Class allocation (used by aggregator for classification):
#   ids 1..16     = elephants (4 MB)
#   ids 17..272   = mice (32 KB) in 8 waves
mice_lines = []
fid = 0
# Elephants
hosts = list(range(N))
e_src = rng.sample(hosts, 16)
e_dst = rng.sample(hosts, 16)
for i in range(16):
    if e_src[i] == e_dst[i]:
        e_dst[i] = (e_dst[i] + 1) % N
for s, d in zip(e_src, e_dst):
    fid += 1
    mice_lines.append(f"{s}->{d} id {fid} start 0 size 4194304")
# Mice: 256 flows in 8 waves of 32 every 30 us
for k in range(256):
    s = rng.randrange(N); d = rng.randrange(N)
    while d == s: d = rng.randrange(N)
    wave = k % 8
    start_us = 10 + wave * 30
    fid += 1
    mice_lines.append(f"{s}->{d} id {fid} start {start_us * US} size 32768")
write_cm(os.path.join(HERE, "mice_heavy.cm"), mice_lines)

# ---------------- elephant-heavy ----------------
# All ids = elephants (16 MB)
elephant_lines = []
fid = 0
e_src = rng.sample(hosts, 64)
e_dst = rng.sample(hosts, 64)
for i in range(64):
    if e_src[i] == e_dst[i]:
        e_dst[i] = (e_dst[i] + 1) % N
for s, d in zip(e_src, e_dst):
    fid += 1
    elephant_lines.append(f"{s}->{d} id {fid} start 0 size 16777216")
write_cm(os.path.join(HERE, "elephant_heavy.cm"), elephant_lines)

print("\nNote: composite.cm is generated by gen_composite.py (same dir).")
print("      Pure-permutation TM is reused: htsim/sim/datacenter/connection_matrices/perm_n128_s8388608.cm")
