#!/usr/bin/env python3
"""Generate k-ary 3-tier fat-tree .topo files (1:1, k even) for the Ofan paper repro (arXiv 2610.07230).
nodes = k^3/4, Podsize = k^2/4, tier0/1: Radix_Down = Radix_Up = k/2, tier2 Radix_Down = k.
Default 800 Gbps and 0.5 us per link (paper). Template: htsim/sim/datacenter/topologies/reps/fat_tree_54_1os_3t_400g.topo
Usage: gen_topo.py [outdir] [--gbps 800] [--lat_ns 500] [--k 4 6 8 ...]
Output name: fat_tree_<nodes>_1os_3t_<gbps>g.topo   (k=4,6,8,10,12,16 -> 16,54,128,250,432,1024 hosts)"""
import argparse, os
HERE = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser()
ap.add_argument("outdir", nargs="?", default=os.path.join(HERE, "..", "topologies"))
ap.add_argument("--gbps", type=int, default=800)
ap.add_argument("--lat_ns", type=int, default=500)
ap.add_argument("--k", type=int, nargs="*", default=[4, 6, 8, 10, 12, 16])
a = ap.parse_args()
os.makedirs(a.outdir, exist_ok=True)
for k in a.k:
    assert k % 2 == 0
    n, pod, h = k**3 // 4, k * k // 4, k // 2
    txt = f"""# k={k} 3-tier fat-tree: {n} hosts, {h*h} core switches, 1:1 oversubscription (generated by gen_topo.py)
Nodes {n}
Tiers 3
Podsize {pod}

Tier 0
Oversubscribed 1
Downlink_speed_Gbps {a.gbps}
Radix_Down {h}
Radix_Up {h}
Downlink_Latency_ns {a.lat_ns}
Switch_Latency_ns 0

Tier 1
Oversubscribed 1
Downlink_speed_Gbps {a.gbps}
Radix_Down {h}
Radix_Up {h}
Downlink_Latency_ns {a.lat_ns}
Switch_Latency_ns 0
Bundle 1

Tier 2
Downlink_speed_Gbps {a.gbps}
Radix_Down {k}
Downlink_Latency_ns {a.lat_ns}
Switch_Latency_ns 0
Bundle 1
"""
    p = os.path.join(a.outdir, f"fat_tree_{n}_1os_3t_{a.gbps}g.topo")
    open(p, "w", newline="\n").write(txt)
    print(p, "hosts", n, "podsize", pod)
