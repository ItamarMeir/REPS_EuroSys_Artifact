#!/usr/bin/env python3
"""
exp26 driver — fig_2_symmetric (--figure fig2) and fig_4_asymmetric (--figure fig4).

fig_2 and fig_4 share the same three sub-panels and command templates; fig_4
only adds ``-failed 4`` to every run (plus ``-skip_asy`` on the micro panel), and
its micro panel uses the 128-host topology instead of 1024.

Templates copied verbatim from:
  micro : htsim/sim/datacenter/run_symmetric.py:10   (-enable_qa_gate, -q 101, -ecn 25 76)
  dc    : htsim/sim/datacenter/run_dc.py:32          (-q 100, -ecn 25 76, seed 1019)
  ai    : htsim/sim/datacenter/run_collective.py:31  (+ -down_ratio, -q 100, seed 1019)

Panel matrices:
  micro : {perm, tornado, incast_d8} x sizes {4194304, 8388608, 16777216}
          (regenerated by run_symmetric.py at the panel's topology size; the
           filenames are topology-keyed, perm_n<hosts>_s<size>.cm, so they never
           collide with another figure)
  dc    : {40,60,80,100}load_ae.cm -- the 32-rank "artifact evaluation" matrices.
          These run on the 128-host topology ON PURPOSE: run_dc.py's --ae_runs
          defaults to True and run_all_symm.py never overrides it, so the paper's
          own fig_2/fig_4 dc panel does exactly the same. gen_files_remote.py
          never writes *_ae.cm at all (it writes {load}.cm / {load}load_32.cm and
          skips existing files), so these are git-tracked fixtures.
  ai    : {alltoall4, alltoall8, alltoall16, allreduce, allreduce_t}
          -down_ratio 0.25 for allreduce, 0.5 otherwise

exp26 change: LB sweep -> {ops, reps_b1..reps_b<n_paths>}, every run + -use_srv6,
-paths = n_paths for that panel's topology.

CONNECTION-MATRIX COLLISION (--prep-cms): the five collective .cm files are NOT
topology-keyed -- fig_7 regenerates them at 32 ranks (run_all_failure.py:54) and
fig_2/fig_4 regenerate them at 128 ranks (run_all_symm.py:75, run_all_asy.py:57),
overwriting each other in place. The ai panel therefore generates the 128-rank
versions before running and restores the git-tracked 32-rank ones afterwards, so
fig_7 stays reproducible from a clean tree.
"""
from __future__ import annotations

import argparse
import itertools
import shutil
import subprocess

from common import (DC_DIR, PATHS, RUNS_DIR, arm_lb_flags, arms_for, emit,
                    get_bdp, run_one)

# Every matrix gen_files.py overwrites (all_to_all_n = [1,2,4,8,16] plus the two
# all-reduces); alltoall4/8/16 + allreduce{,_t} are the ones fig_7 and fig_2/4
# both consume, but all seven must be put back or the tree is left dirty.
COLLECTIVE_CMS = ["alltoall1", "alltoall2", "alltoall4", "alltoall8",
                  "alltoall16", "allreduce", "allreduce_t"]
CM_DIR = DC_DIR / "connection_matrices"
BAK_SUFFIX = ".exp26bak"

_BDP = get_bdp(400000, 2, 1000)
MICRO_Q = int(_BDP)                       # 101
MICRO_ECN = (int(_BDP / 4), int(_BDP * 3 / 4))   # (25, 76)
MICRO_CWND = int(MICRO_Q * 1.5)           # 151

MICRO_SIZES = [4194304, 8388608, 16777216]
MICRO_PATTERNS = ["perm", "tornado", "incast"]     # incast -> _d8 suffix

DC_TMS = ["40load_ae", "60load_ae", "80load_ae", "100load_ae"]
# --dc-full: the 128-rank DC matrices (git-tracked; used when run_dc.py runs
# with --ae_runs falsy). Much heavier (~6x the flows).
DC_TMS_FULL = ["40load", "60load", "80load", "100load"]
AI_TMS = ["alltoall4", "alltoall8", "alltoall16", "allreduce", "allreduce_t"]

MICRO_SEED = 42
DC_SEED = 1019
AI_SEED = 1019


def gen_collective_cms(topo_n: int) -> None:
    """Mirror run_all_symm.py:75 / run_all_asy.py:57 -- build the collective
    matrices at this panel's topology size (gen_files.py overwrites in place).

    Each existing file is copied aside first so restore_collective_cms() can put
    the tree back byte-for-byte. Plain file copies, not `git checkout`: the
    restore must work even when the repo index is locked or the files were
    already dirty.
    """
    for name in COLLECTIVE_CMS:
        src = CM_DIR / f"{name}.cm"
        if src.exists():
            shutil.copy2(src, src.with_suffix(f".cm{BAK_SUFFIX}"))
    cmd = ["python3", "connection_matrices/gen_files.py",
           "--size_topo", str(topo_n), "--all_red_size", str(topo_n)]
    print(f"  prep: {' '.join(cmd)}  (backed up {len(COLLECTIVE_CMS)} .cm)",
          flush=True)
    subprocess.run(cmd, cwd=str(DC_DIR), check=True)


def restore_collective_cms() -> None:
    """Put the pre-existing (32-rank) collective matrices back, so fig_7 -- which
    consumes the same filenames at 32 ranks -- stays reproducible."""
    n = 0
    for name in COLLECTIVE_CMS:
        bak = CM_DIR / f"{name}.cm{BAK_SUFFIX}"
        if bak.exists():
            shutil.move(str(bak), str(CM_DIR / f"{name}.cm"))
            n += 1
    print(f"  restore: put back {n} collective .cm", flush=True)


def micro_tm(pattern: str, size: int, topo_n: int) -> str:
    if pattern == "incast":
        return f"connection_matrices/incast_n{topo_n}_s{size}_d8.cm"
    return f"connection_matrices/{pattern}_n{topo_n}_s{size}.cm"


def micro_flags(tm: str, topo_key: str, failed: bool) -> list[str]:
    f = ["-connections_mapping", "-disable_trim"]
    if failed:
        f += ["-failed", "4", "-skip_asy"]
    f += [
        "-sack_threshold", "4000",
        "-tm", tm,
        "-end", "90000",
        "-seed", str(MICRO_SEED),
        "-sender_cc_only", "-sender_cc_algo", "mprdma",
        "-topo", f"topologies/reps/{topo_key}.topo",
        "-enable_qa_gate",
        "-linkspeed", "400000",
        "-ecn", str(MICRO_ECN[0]), str(MICRO_ECN[1]),
        "-q", str(MICRO_Q),
        "-cwnd", str(MICRO_CWND),
    ]
    return f


def dc_flags(tm: str, failed: bool) -> list[str]:
    f = ["-disable_trim"]
    if failed:
        f += ["-failed", "4"]
    f += [
        "-connections_mapping",
        "-sack_threshold", "4000",
        "-end", "90000",
        "-seed", str(DC_SEED),
        "-sender_cc_only", "-sender_cc_algo", "mprdma",
        "-topo", "topologies/reps/fat_tree_128_1os_2t_400g.topo",
        "-linkspeed", "400000",
        "-ecn", "25", "76",
        "-q", "100",
        "-cwnd", "151",
        "-tm", f"connection_matrices/{tm}.cm",
    ]
    return f


def ai_flags(tm: str, failed: bool) -> list[str]:
    ratio = "0.25" if tm == "allreduce" else "0.5"
    f = ["-disable_trim"]
    if failed:
        f += ["-failed", "4"]
    f += [
        "-connections_mapping",
        "-down_ratio", ratio,
        "-sack_threshold", "4000",
        "-end", "90000",
        "-seed", str(AI_SEED),
        "-sender_cc_only", "-sender_cc_algo", "mprdma",
        "-topo", "topologies/reps/fat_tree_128_1os_2t_400g.topo",
        "-linkspeed", "400000",
        "-ecn", "25", "76",
        "-q", "100",
        "-cwnd", "151",
        "-tm", f"connection_matrices/{tm}.cm",
    ]
    return f


def build_cells(figure: str, panels: list[str], quick: bool,
                dc_full: bool = False):
    """Yield (panel, workload, condition, topo_key, n_paths, base_flags, expect_cm_nodes).

    ``expect_cm_nodes`` is the connection-matrix rank count run_one() should see;
    ``None`` means "must equal the topology's host count". Only the dc panel
    overrides it (32-rank ``*load_ae.cm`` on 128 hosts -- see module docstring).
    """
    failed = figure == "fig4"
    micro_topo_key = "fat_tree_128_1os_2t_400g" if failed else "fat_tree_1024_1os_2t_400g"
    micro_n = PATHS[micro_topo_key]
    dc_n = ai_n = PATHS["fat_tree_128_1os_2t_400g"]
    cond = "asym4" if failed else "healthy"

    out = []
    if "micro" in panels:
        patterns = ["perm"] if quick else MICRO_PATTERNS
        sizes = [8388608] if quick else MICRO_SIZES
        for pat, size in itertools.product(patterns, sizes):
            topo_n = int(micro_topo_key.split("_")[2])
            tm = micro_tm(pat, size, topo_n)
            wl = f"{pat}_s{size}"
            out.append(("micro", wl, cond, micro_topo_key, micro_n,
                        micro_flags(tm, micro_topo_key, failed), None))
    if "dc" in panels:
        pool = DC_TMS_FULL if dc_full else DC_TMS
        tms = [pool[-1]] if quick else pool
        for tm in tms:
            out.append(("dc", tm, cond, "fat_tree_128_1os_2t_400g", dc_n,
                        dc_flags(tm, failed), None if dc_full else 32))
    if "ai" in panels:
        tms = ["allreduce"] if quick else AI_TMS
        for tm in tms:
            out.append(("ai", tm, cond, "fat_tree_128_1os_2t_400g", ai_n,
                        ai_flags(tm, failed), None))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--figure", required=True, choices=["fig2", "fig4"])
    ap.add_argument("--panels", default="micro,dc,ai")
    ap.add_argument("--arms", default="")
    ap.add_argument("--quick", action="store_true")
    ap.add_argument("--prep-cms", action="store_true",
                    help="regenerate the collective .cm files at the ai panel's "
                         "topology size first, then restore the git-tracked "
                         "32-rank ones (which fig_7 needs) on the way out")
    ap.add_argument("--dc-full", action="store_true",
                    help="dc panel: use the 128-rank {40,60,80,100}load.cm "
                         "instead of the 32-rank *load_ae.cm (~6x heavier)")
    args = ap.parse_args()

    panels = args.panels.split(",")
    cells = build_cells(args.figure, panels, args.quick, args.dc_full)

    # expand over arms
    expanded = []
    for (panel, wl, cond, topo_key, n_paths, bflags, expect_cm) in cells:
        arms = arms_for(n_paths)
        if args.quick:
            arms = ["ops", "reps_b1", f"reps_b{n_paths}"]
        if args.arms:
            arms = [a for a in arms if a in args.arms.split(",")]
        for arm in arms:
            expanded.append((panel, wl, cond, topo_key, n_paths, bflags,
                             expect_cm, arm))

    total = len(expanded)
    print(f"{args.figure}: {total} runs  (panels={panels})", flush=True)

    prep = args.prep_cms and "ai" in panels
    if prep:
        gen_collective_cms(int("fat_tree_128_1os_2t_400g".split("_")[2]))

    fails = warns = 0
    try:
        for i, (panel, wl, cond, topo_key, n_paths, bflags, expect_cm,
                arm) in enumerate(expanded, 1):
            outfile = RUNS_DIR / args.figure / panel / wl / cond / arm / "stdout.txt"
            flags = bflags + arm_lb_flags(arm, n_paths)
            res = run_one(flags, outfile, cwd=DC_DIR, expect_cm_nodes=expect_cm)
            emit(i, total, f"{panel}/{wl}/{arm}", res)
            if res["status"].startswith("FAIL"):
                fails += 1
            if res.get("cm_warn"):
                warns += 1
    finally:
        if prep:
            restore_collective_cms()

    print(f"\n{args.figure} done: {fails} failures / {total}"
          f"{f', {warns} CONNECTION-MATRIX WARNINGS' if warns else ''}", flush=True)


if __name__ == "__main__":
    main()
