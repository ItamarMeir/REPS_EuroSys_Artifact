#!/usr/bin/env python3
"""Plot PATH_STATIC cwnd vs time: constant CC (flat) vs NSCC (AI-driven growth).

Reads:  /tmp/cwnd_trace/{const,nscc}_cwnd.csv   (generated by 01_run_exp17_cwnd_trace.sh)
Writes: plots/exp17_cwnd_trace.png
"""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT  = Path(__file__).resolve().parent
PLOTS = ROOT / "plots"
PLOTS.mkdir(exist_ok=True)

TRACE_DIR = Path("/tmp/cwnd_trace")
CONST_CSV = TRACE_DIR / "const_cwnd.csv"
NSCC_CSV  = TRACE_DIR / "nscc_cwnd.csv"

BDP_PKTS      = 150.7   # unloaded BDP at 400 Gbps, 12.5 µs RTT, 4150 B MTU
ECN_LOW_PKTS  = 12      # -ecn 12 48 low threshold
ECN_HIGH_PKTS = 48


def load(path, stride=1):
    """Load CSV with pandas; keep every stride-th row.
    Returns (time_us, src_id, cwnd_pkts) as numpy arrays."""
    df = pd.read_csv(path)[::stride]
    return df["time_us"].to_numpy(), df["src_id"].to_numpy(int), df["cwnd_pkts"].to_numpy(int)


def aggregate(times, cwnds, bin_us, t_lo=None, t_hi=None):
    """Bin into bin_us buckets; optionally restrict to [t_lo, t_hi].
    Returns (t_centers, mean, p5, p95)."""
    if t_lo is not None:
        mask = (times >= t_lo) & (times <= t_hi)
        times, cwnds = times[mask], cwnds[mask]
    s    = pd.Series(cwnds, dtype=float)
    bins = pd.cut(times, bins=np.arange(times.min(), times.max() + bin_us, bin_us))
    grp  = s.groupby(bins)
    centers = np.array([iv.mid for iv in grp.mean().index])
    return centers, grp.mean().to_numpy(), grp.quantile(0.05).to_numpy(), grp.quantile(0.95).to_numpy()


def main():
    if not CONST_CSV.exists() or not NSCC_CSV.exists():
        print(f"ERROR: run 01_run_exp17_cwnd_trace.sh first to generate traces in {TRACE_DIR}")
        return

    print("Loading constant trace…")
    ct, _, cc = load(CONST_CSV)
    const_cwnd_val = int(np.median(cc))

    print("Loading NSCC trace…")
    nt, _, nc = load(NSCC_CSV)

    # time values are in nanoseconds (now()/1000 in the log). Convert to µs for display.
    nt_us = nt / 1e3

    # Overview: 200 µs bins over full trace (in µs)
    print("Aggregating overview…")
    t_ov, ov_mean, ov_p5, ov_p95 = aggregate(nt_us, nc, bin_us=200)

    # Zoom: 0.5 µs bins over the ramp-up phase (first 60 µs)
    zoom_lo, zoom_hi = nt_us.min(), nt_us.min() + 60
    print(f"Aggregating zoom ({zoom_lo:.1f}–{zoom_hi:.1f} µs, ramp-up phase)…")
    t_zm, zm_mean, zm_p5, zm_p95 = aggregate(nt_us, nc, bin_us=0.5, t_lo=zoom_lo, t_hi=zoom_hi)

    t0, t1 = nt_us.min(), nt_us.max()

    fig, (ax_ov, ax_zm) = plt.subplots(1, 2, figsize=(14, 4),
                                        gridspec_kw={"width_ratios": [2, 1]})
    fig.suptitle(
        "PATH_STATIC cwnd — 256 MiB tornado, cwnd_init=155, seed=42\n"
        "Constant CC: fixed. NSCC: AI/MD oscillates near maxwnd = 1.5×BDP.",
        fontsize=9)

    def draw_panel(ax, t_us, mean, p5, p95, xlim_us, bin_label, ylim):
        ax.fill_between(t_us, p5, p95, alpha=0.3, color="#E65100", label="NSCC p5–p95")
        ax.plot(t_us, mean, color="#E65100", linewidth=1.0, label="NSCC mean")
        ax.hlines(const_cwnd_val, *xlim_us,
                  colors="#1565C0", linewidths=1.5, label=f"Constant = {const_cwnd_val}")
        ax.axhline(229, color="#E65100", linewidth=0.6, linestyle=":", label="maxwnd = 229")
        if ylim[0] < 160:
            ax.axhline(BDP_PKTS, color="black", linewidth=0.8, linestyle="--",
                       label=f"BDP ≈ {BDP_PKTS:.0f}")
        ax.set_xlabel(f"Time (µs)  [{bin_label}]")
        ax.set_ylabel("cwnd (packets)")
        ax.set_xlim(*xlim_us)
        ax.set_ylim(*ylim)
        ax.legend(fontsize=7)

    draw_panel(ax_ov, t_ov, ov_mean, ov_p5, ov_p95, (t0, t1),
               "200 µs bins — overview", ylim=(148, 235))
    draw_panel(ax_zm, t_zm, zm_mean, zm_p5, zm_p95, (zoom_lo, zoom_hi),
               "0.5 µs bins — 60 µs ramp-up (158→229 pkts)", ylim=(155, 235))

    # Highlight zoom window on overview
    ax_ov.axvspan(zoom_lo, zoom_hi, alpha=0.1, color="gray", label="zoom region")

    plt.tight_layout()
    out = PLOTS / "exp17_cwnd_trace.png"
    fig.savefig(out, dpi=150, bbox_inches="tight")
    print(f"Saved {out}")

    valid = ov_mean[~np.isnan(ov_mean)]
    print(f"\nNSCC cwnd (overview mean):  min={valid.min():.1f}  max={valid.max():.1f}  "
          f"mean={valid.mean():.1f}")
    print(f"Constant cwnd: {const_cwnd_val}  |  Unloaded BDP: {BDP_PKTS:.1f}  |  maxwnd: 229")


if __name__ == "__main__":
    main()
